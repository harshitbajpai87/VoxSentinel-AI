import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()) })
await page.goto('http://localhost:5173/protection', { waitUntil: 'networkidle' })
await page.waitForTimeout(1200)
const item = page.locator('ul li button').first()
await item.click()
await page.waitForSelector('text=Analysis result', { timeout: 40000 })
await page.waitForTimeout(600)
const t = (await page.locator('body').innerText()).toLowerCase()
console.log('gemini section labelled:', t.includes('gemini ai contextual analysis') ? 'YES' : 'NO')
console.log('honest fallback shown:', /not configured|rule-based fallback/.test(t) ? 'YES' : 'NO')
console.log('rule baseline still shown:', t.includes('content analysis') || t.includes('detected indicators') ? 'YES' : 'NO')
console.log('voice section shown:', t.includes('voice authenticity') ? 'YES' : 'NO')
console.log('risk shown:', /(low|medium|high|critical|inconclusive) risk/.test(t) ? 'YES' : 'NO')
console.log('console errors:', errs.length ? errs.slice(0,2) : 'none')
await browser.close()
